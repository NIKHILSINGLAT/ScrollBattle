package com.scrollbattle.service

import android.accessibilityservice.AccessibilityService
import android.accessibilityservice.AccessibilityServiceInfo
import android.content.Intent
import android.view.accessibility.AccessibilityEvent
import com.scrollbattle.MainActivity
import com.scrollbattle.data.DefaultScrollBattleRepository
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.flow.collectLatest
import kotlinx.coroutines.launch

class ScrollBattleAccessibilityService : AccessibilityService() {

    private val serviceScope = CoroutineScope(Dispatchers.Main + SupervisorJob())
    private lateinit var repository: DefaultScrollBattleRepository
    private lateinit var overlayManager: FloatingOverlayManager

    private var currentPackage: String? = null
    private var lastLimitEnforcementTimestamp = 0L
    private var reelsFeedActive = false

    companion object {
        var isServiceRunning = false
            private set
    }

    override fun onServiceConnected() {
        super.onServiceConnected()
        isServiceRunning = true

        repository = DefaultScrollBattleRepository.getInstance(applicationContext)
        overlayManager = FloatingOverlayManager(this)

        val info = AccessibilityServiceInfo().apply {
            eventTypes = AccessibilityEvent.TYPE_VIEW_SCROLLED or
                    AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED or
                    AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED
            feedbackType = AccessibilityServiceInfo.FEEDBACK_GENERIC
            notificationTimeout = 100
            packageNames = arrayOf("com.instagram.android")
            flags = AccessibilityServiceInfo.FLAG_REPORT_VIEW_IDS
        }
        serviceInfo = info

        repository.refreshPermissions(applicationContext)

        val filter = android.content.IntentFilter().apply {
            addAction("com.scrollbattle.ACTION_SHOW_PILL")
            addAction("com.scrollbattle.ACTION_SHOW_INTERRUPTION")
            addAction("com.scrollbattle.ACTION_HIDE_OVERLAYS")
        }
        androidx.core.content.ContextCompat.registerReceiver(
            this,
            testReceiver,
            filter,
            androidx.core.content.ContextCompat.RECEIVER_NOT_EXPORTED
        )

        // Observe state changes in real time
        serviceScope.launch {
            repository.state.collectLatest { state ->
                val instagramIsForeground =
                    rootInActiveWindow?.packageName?.toString() == "com.instagram.android"
                if (instagramIsForeground && state.todayReels >= state.totalAllowance) {
                    // Enforce the daily lock on every Instagram screen, not only Reels.
                    enforceLimitIfExceeded()
                } else if (instagramIsForeground && isReelsActive()) {
                    overlayManager.hideInterruption()
                    overlayManager.showPill(state.todayReels, state.totalAllowance)
                } else {
                    overlayManager.hideAll()
                }
            }
        }
    }

    private var lastSwipeTimestamp = 0L
    private var lastContentCheckTimestamp = 0L

    private fun isTargetApp(pkg: String?): Boolean {
        return pkg == "com.instagram.android"
    }

    private fun enforceLimitIfExceeded(force: Boolean = false): Boolean {
        val state = repository.state.value
        if (state.todayReels < state.totalAllowance) return false

        // Debounce the burst of accessibility events generated by one app launch.
        // Do not use a permanent latch: the user may reopen Instagram and must be blocked again.
        val now = System.currentTimeMillis()
        if (!force && now - lastLimitEnforcementTimestamp < 1_500L) return true
        lastLimitEnforcementTimestamp = now

        overlayManager.hideAll()
        // Android cannot force-stop another app. Return to Home, then show the lock screen.
        performGlobalAction(GLOBAL_ACTION_HOME)
        val intent = Intent(this, MainActivity::class.java).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP or Intent.FLAG_ACTIVITY_SINGLE_TOP
            putExtra("destination", "limit_reached")
        }
        startActivity(intent)
        return true
    }

    private fun hasViewId(root: android.view.accessibility.AccessibilityNodeInfo, viewId: String): Boolean {
        val matches = root.findAccessibilityNodeInfosByViewId(viewId)
        val found = matches.isNotEmpty()
        matches.forEach { it.recycle() }
        return found
    }

    private fun hasText(root: android.view.accessibility.AccessibilityNodeInfo, text: String): Boolean {
        val matches = root.findAccessibilityNodeInfosByText(text)
        val found = matches.isNotEmpty()
        matches.forEach { it.recycle() }
        return found
    }

    private fun isReelsActive(eventSource: android.view.accessibility.AccessibilityNodeInfo? = null): Boolean {
        val activeRoot = rootInActiveWindow
        val root = when {
            activeRoot?.packageName?.toString() == "com.instagram.android" -> activeRoot!!
            eventSource?.packageName?.toString() == "com.instagram.android" -> eventSource!!
            else -> return false
        }
        try {
            // Exclude Direct Messages and other non-video screens
            if (hasViewId(root, "com.instagram.android:id/direct_thread_layout")) return false

            // Direct checks for verified short-video containers (from BrainPal reverse-engineering)
            val containerIds = listOf(
                "com.instagram.android:id/clips_viewer_view_pager",
                "com.instagram.android:id/clips_video_container",
                "com.instagram.android:id/clips_media_component",
                "com.instagram.android:id/reel_viewer",
                "com.instagram.android:id/clips_swipe_refresh_container",
                "com.instagram.android:id/clips_action_bar_container",
                "com.instagram.android:id/reel_viewer_media_layout",
             )
            for (id in containerIds) {
                if (hasViewId(root, id)) return true
            }

            // Check event source's ID
            val sourceId = eventSource?.viewIdResourceName ?: ""
            if (sourceId.contains("clips") || sourceId.contains("reel") || sourceId.contains("spotlight")) {
                return true
            }

            // Fallback: Check for distinct Reels UI text markers (for newer or obfuscated Instagram builds)
            val reelsMarkers = listOf("Original audio", "Reel by", "Use audio")
            for (marker in reelsMarkers) {
                if (hasText(root, marker)) {
                    val homeHeader = hasText(root, "Instagram")
                    val homeLogo = hasViewId(root, "com.instagram.android:id/action_bar_home_logo")
                    if (!homeHeader && !homeLogo) return true
                }
            }
        } catch (e: Exception) {
            // ignore
        }
        return false
    }

    private fun isReelPagerScroll(event: AccessibilityEvent): Boolean {
        var node = event.source ?: return false
        repeat(12) {
            val id = node.viewIdResourceName.orEmpty().lowercase()
            if (
                id.contains("clips_viewer") ||
                id.contains("clips_video") ||
                id.contains("clips_media") ||
                id.contains("clips_swipe_refresh") ||
                id.contains("reel_viewer")
            ) return true
            node = node.parent ?: return false
        }
        return false
    }

    override fun onAccessibilityEvent(event: AccessibilityEvent?) {
        val eventPackage = event?.packageName?.toString() ?: return

        // Track only Instagram. Other apps must never trigger Reel enforcement.
        if (!isTargetApp(eventPackage)) {
            if (event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED) {
                currentPackage = eventPackage
                reelsFeedActive = false
                overlayManager.hideAll()
            }
            return
        }

        repository.refreshDailyBoundary()

        if (event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED) {
            currentPackage = eventPackage
        }

        // The 50-Reel lock applies to the entire Instagram app, including DMs, profiles and feed.
        // Check before testing whether the current screen is the Reels viewer.
        if (repository.state.value.todayReels >= repository.state.value.totalAllowance) {
            enforceLimitIfExceeded(force = event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED)
            return
        }

        // Throttle noisy layout-change events before traversing the accessibility tree.
        if (event.eventType == AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED) {
            val now = System.currentTimeMillis()
            if (now - lastContentCheckTimestamp < 800L) return
            lastContentCheckTimestamp = now
        }

        // Enforce only while the Instagram short-video feed is actually detected.
        val reelsActive = isReelsActive(event.source)
        if (!reelsActive) {
            reelsFeedActive = false
            if (overlayManager.isPillVisible) overlayManager.hidePill()
            return
        }

        // Count the first Reel when the user enters the Reel feed, not only later swipes.
        if (!reelsFeedActive) {
            reelsFeedActive = true
            if (enforceLimitIfExceeded()) return
            lastSwipeTimestamp = System.currentTimeMillis()
            repository.recordReelTransition("Instagram Reels")
            if (enforceLimitIfExceeded()) return
            val state = repository.state.value
            overlayManager.showPill(state.todayReels, state.totalAllowance)
            return
        }

        if (enforceLimitIfExceeded()) return

        // 1. App or Window transition
        if (event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED) {
            val oldPackage = currentPackage
            currentPackage = eventPackage

            if (isTargetApp(oldPackage) && !isTargetApp(eventPackage)) {
                // User navigated away from target short-video app
                overlayManager.hideAll()
                return
            }

            if (isTargetApp(eventPackage)) {
                if (isReelsActive(event.source)) {
                    val state = repository.state.value
                    overlayManager.showPill(state.todayReels, state.totalAllowance)
                } else {
                    // Inside target app but not in Reels (e.g. DMs, Profile, Feed) -> hide pill
                    overlayManager.hidePill()
                }
            }
        }

        // The feed state was already checked above for this throttled content-change event.
        if (event.eventType == AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED) return

        // 3. ONLY ON ACTUAL VERTICAL SHORT-VIDEO SCROLL
        if (event.eventType == AccessibilityEvent.TYPE_VIEW_SCROLLED && isTargetApp(eventPackage)) {
            // Ignore horizontal swipes (stories or photo carousels)
            if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.P) {
                val deltaY = event.scrollDeltaY
                val deltaX = event.scrollDeltaX
                if (deltaX != 0 && deltaY == 0) {
                    return
                }
            }

            // Only count vertical scrolls originating in the Reel pager hierarchy.
            if (!isReelPagerScroll(event)) {
                return
            }

            // Strict debounce: minimum 250ms between reel increments
            val now = System.currentTimeMillis()
            if (now - lastSwipeTimestamp < 250L) {
                return
            }
            lastSwipeTimestamp = now

            repository.recordReelTransition("Instagram Reels")

            // If this swipe pushed count to 50, kick user out of Instagram immediately!
            if (enforceLimitIfExceeded()) return

            val state = repository.state.value
            overlayManager.showPill(state.todayReels, state.totalAllowance)
        }
    }

    private val testReceiver = object : android.content.BroadcastReceiver() {
        override fun onReceive(context: android.content.Context?, intent: android.content.Intent?) {
            val state = repository.state.value
            when (intent?.action) {
                "com.scrollbattle.ACTION_SHOW_PILL" -> {
                    overlayManager.showPill(state.todayReels, state.totalAllowance)
                }
                "com.scrollbattle.ACTION_SHOW_INTERRUPTION" -> {
                    overlayManager.showInterruption(
                        currentReels = state.todayReels,
                        totalAllowance = state.totalAllowance,
                        onStartChallenge = {
                            repository.triggerNavigation("maths_challenge")
                            val mainIntent = Intent(this@ScrollBattleAccessibilityService, MainActivity::class.java).apply {
                                flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP
                                putExtra("destination", "maths_challenge")
                            }
                            startActivity(mainIntent)
                        },
                        onDoneForToday = {
                            performGlobalAction(GLOBAL_ACTION_HOME)
                        }
                    )
                }
                "com.scrollbattle.ACTION_HIDE_OVERLAYS" -> {
                    overlayManager.hideAll()
                }
            }
        }
    }

    override fun onInterrupt() {
        if (::overlayManager.isInitialized) overlayManager.hideAll()
    }

    override fun onDestroy() {
        super.onDestroy()
        isServiceRunning = false
        try {
            unregisterReceiver(testReceiver)
        } catch (e: Exception) {
            e.printStackTrace()
        }
        if (::overlayManager.isInitialized) overlayManager.hideAll()
        serviceScope.cancel()
    }
}
